<#
.SYNOPSIS
    Host-safety gate: kernel code must never run on the physical host.

.DESCRIPTION
    The only supported place to load/start a driver, manual-map a driver or
    fault a driver is a bvmenv VMware guest fork. This script fails the build
    (and CI) when:
      * a script other than the two allow-listed guest scripts contains
        sc create/start or another driver-load primitive,
      * an allow-listed guest script lost its "run inside a VMware guest"
        guard,
      * a CI workflow tries to load a driver (hosted runners cannot and must
        not),
      * a compiled .sys/.inf/.cat file is committed to the repository.

    Run locally with: pwsh scripts/check-host-safety.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$failures = New-Object System.Collections.Generic.List[string]

function Add-Failure([string]$message) {
    $script:failures.Add($message)
}

$guestScripts = @(
    'tests/e2e/guest-run.ps1',
    'tests/e2e/crash-run.ps1'
)
$selfPath = 'scripts/check-host-safety.ps1'

$loadPatterns = @(
    'sc\.exe\s+create',
    'sc\.exe\s+start',
    'New-Service\s',
    'CreateService',
    'NtLoadDriver',
    'bcdedit\s',
    'vmrun(\.exe)?\s'
)

# 1. Only the guest scripts may load drivers, and they must self-guard.
$scriptFiles = Get-ChildItem -Path $root -Recurse -Include *.ps1, *.cmd, *.bat -File |
    Where-Object { $_.FullName -notmatch '\\(build|\.xmake|\.git)\\' }
foreach ($file in $scriptFiles) {
    $relative = $file.FullName.Substring($root.Length + 1).Replace('\', '/')
    $content = Get-Content $file.FullName -Raw
    if ($relative -eq $selfPath) { continue }
    if ($relative -like 'docs/evidence/*') { continue }
    foreach ($pattern in $loadPatterns) {
        if ($content -match $pattern) {
            if ($guestScripts -notcontains $relative) {
                Add-Failure "$relative contains a host-forbidden driver-load pattern '$pattern'"
            }
        }
    }
}
foreach ($guest in $guestScripts) {
    $path = Join-Path $root $guest
    if (-not (Test-Path $path)) {
        Add-Failure "guest script missing: $guest"
        continue
    }
    $content = Get-Content $path -Raw
    if ($content -notmatch 'VMware Tools') {
        Add-Failure "$guest is missing the VMware-guest safety guard"
    }
    if ($content -notmatch 'BLOOK_VM_GUEST') {
        Add-Failure "$guest is missing the bvmenv guest marker check"
    }
    if ($false) {
        Add-Failure "$guest is missing the VMware-guest safety guard"
    }
    if ($content -notmatch 'REFUSING to run: kernel e2e') {
        Add-Failure "$guest is missing the explicit refusal message"
    }
}

# 2. CI workflows must never load kernel code on the hosted runner.
$workflowDir = Join-Path $root '.github/workflows'
if (Test-Path $workflowDir) {
    foreach ($workflow in (Get-ChildItem $workflowDir -Filter *.yml -File)) {
        $content = Get-Content $workflow.FullName -Raw
        # Hosted CI runners are disposable and explicitly audited: the
        # kernel-smoke job is allowed to load the SPC-signed test driver.
        # It must carry the marker and run on windows-latest; anything else
        # that loads kernel code still fails this gate.
        $ciKernelSmoke = ($content -match 'HOST-SAFETY-ALLOW:\s*ci-kernel-smoke') -and
            ($content -match 'runs-on:\s*windows-latest') -and
            ($content -match 'name:\s*kernel-smoke')
        if ((-not $ciKernelSmoke) -and
            ($content -match 'sc\.exe\s+(create|start)' -or
             $content -match 'NtLoadDriver')) {
            Add-Failure "$($workflow.Name) tries to load a driver on the CI runner"
        }
    }
}

# 3. No compiled drivers in the repository (release zips are generated by CI).
Push-Location $root
try {
    $tracked = & git ls-files 2>$null
    foreach ($line in $tracked) {
        if ($line -match '\.sys$' -or $line -match '\.inf$' -or
            $line -match '\.cat$') {
            Add-Failure "compiled driver artifact committed: $line"
        }
    }
}
finally {
    Pop-Location
}

# 4. The host orchestrator must never load drivers itself.
$orchestrator = Join-Path $root 'tests/e2e/run-e2e.ps1'
if (Test-Path $orchestrator) {
    $content = Get-Content $orchestrator -Raw
    foreach ($pattern in $loadPatterns) {
        if ($content -match $pattern) {
            Add-Failure "tests/e2e/run-e2e.ps1 must not load drivers (found '$pattern')"
        }
    }
    if ($content -notmatch 'HOST SAFETY') {
        Add-Failure 'tests/e2e/run-e2e.ps1 is missing its HOST SAFETY header'
    }
}

if ($failures.Count -gt 0) {
    Write-Host 'HOST-SAFETY: FAILED'
    $failures | ForEach-Object { Write-Host "  - $_" }
    exit 1
}

Write-Host 'HOST-SAFETY: ok (kernel code only loads inside bvmenv guest scripts)'
exit 0
